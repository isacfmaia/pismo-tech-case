CREATE TABLE accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_number VARCHAR(50) NOT NULL,
    CONSTRAINT uk_accounts_document_number UNIQUE (document_number)
);

CREATE TABLE operation_types (
    operation_type_id SMALLINT PRIMARY KEY,
    description VARCHAR(100) NOT NULL
);

CREATE TABLE transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    operation_type_id SMALLINT NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    event_date TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_transactions_account
        FOREIGN KEY (account_id) REFERENCES accounts (account_id),
    CONSTRAINT fk_transactions_operation_type
        FOREIGN KEY (operation_type_id) REFERENCES operation_types (operation_type_id),
    CONSTRAINT ck_transactions_amount_non_zero CHECK (amount <> 0)
);
